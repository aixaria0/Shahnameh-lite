import { readdir, readFile, stat } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const roots = ['app', 'lib', 'public', 'README.md', 'next.config.ts', 'package.json'];
const excludedNames = new Set(['node_modules', '.git', '.next', 'dist']);
const forbidden = [
  new RegExp('a' + 'i[ -]?studio', 'i'),
  new RegExp('a' + 'istudio', 'i'),
  new RegExp('artificial[ -]+' + 'intelligence', 'i'),
  new RegExp('a' + 'i[ -]?agent', 'i'),
  new RegExp('agent[ -]+edits', 'i'),
  new RegExp('open' + 'ai', 'i'),
  new RegExp('co' + 'dex', 'i'),
  new RegExp('gr' + 'ok', 'i'),
  new RegExp('fire' + 'base', 'i'),
  /generated by/i,
];

async function collect(target) {
  const full = path.join(root, target);
  const info = await stat(full);
  if (info.isFile()) return [target];
  const out = [];
  for (const name of await readdir(full)) {
    if (excludedNames.has(name)) continue;
    out.push(...await collect(path.join(target, name)));
  }
  return out;
}

const files = (await Promise.all(roots.map(collect))).flat();
const failures = [];
for (const file of files) {
  if (!/\.(?:ts|tsx|js|mjs|json|md|css|svg|txt|woff2)$/.test(file)) continue;
  if (file.endsWith('.woff2')) continue;
  const text = await readFile(path.join(root, file), 'utf8');
  for (const rule of forbidden) if (rule.test(text)) failures.push(`${file}: ${rule}`);
}

if (failures.length) {
  console.error('provenance audit failed');
  console.error(failures.join('\n'));
  process.exit(1);
}
console.log(`provenance audit passed across ${files.length} first-party files`);
